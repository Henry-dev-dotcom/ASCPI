// Bundles explained/<LESSON_ID>.html into ../explained.js for the study app.
// Run from the repo root:  node explained/build.js
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const out = {};
for (const f of fs.readdirSync(dir).filter(f => /^[A-Z]\d+\.html$/.test(f)).sort()) {
  const id = f.replace('.html', '');
  const html = fs.readFileSync(path.join(dir, f), 'utf8').trim();
  const words = html.replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
  out[id] = { min: Math.max(3, Math.round(words / 200)), html };
}
const js = '// Generated by explained/build.js from explained/*.html. Edit those files, not this one.\n' +
  'window.EXPLAINED=' + JSON.stringify(out).replace(/<\//g, '<\\/') + ';\n';
fs.writeFileSync(path.join(dir, '..', 'explained.js'), js);
console.log(Object.keys(out).length + ' lessons bundled, ' + Math.round(js.length / 1024) + ' KB');
